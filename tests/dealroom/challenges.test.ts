import { expect, test } from "vitest";
import { seed } from "@/lib/seed";
import { reducer } from "../helpers";
import { PIPELINE, formGaps, isChallenge, matchable, pipelineOf, validateDealRoom } from "@/lib/dealroom/logic";
import type { AppState } from "@/lib/types";
const ok = (c: unknown, m: string) => test(m, () => expect(c).toBeTruthy());
const dr = seed.dealRoom;
const cfg = dr.configs.ev_ca3;
ok(validateDealRoom(seed).length === 0, "invariants: " + JSON.stringify(validateDealRoom(seed).slice(0, 3)));
const ch = dr.apps.filter(isChallenge);
ok(ch.length === 3, "three challenges");
ok(ch.filter(matchable).length === 2, "two verified challenges are matchable");
const chm = dr.matches.filter((m) => ch.some((c) => c.id === m.providerId));
ok(chm.length > 0, "verified challenges matched to seekers");
ok(!chm.some((m) => m.providerId === "dr_ch03"), "unverified challenge not matched");
const counts = Object.fromEntries(PIPELINE.map((p) => [p, 0]));
for (const a of dr.apps.filter((a) => a.type === "seeker" || a.challenge)) counts[pipelineOf(dr, a, dr.clock).status]++;
ok(counts["Sourced"] > 0 && counts["Under review"] > 0 && counts["Follow-up active"] > 0, "summit day: early statuses and follow-up in use");
const later: AppState = reducer(seed, { type: "dr/clock", clock: "2027-08-18 10:00" } as never);
const c2 = Object.fromEntries(PIPELINE.map((p) => [p, 0]));
for (const a of later.dealRoom.apps.filter((a) => a.type === "seeker" || a.challenge)) c2[pipelineOf(later.dealRoom, a, later.dealRoom.clock).status]++;
ok(PIPELINE.filter((p) => c2[p] > 0).length >= 11, "18 Aug: at least eleven of the thirteen statuses in use");
ok(c2["Committed"] + c2["Closed / deployed"] > 0, "18 Aug: commitments reach the pipeline");
ok(pipelineOf(dr, ch.find((c) => c.id === "dr_ch03")!, dr.clock).status === "Under review", "challenge in review sits Under review");
// a new challenge through the form rules
let s: AppState = seed;
const blankCh = { ...ch[0], id: "dr_new_ch", ref: undefined, status: "Draft" as const, submittedAt: undefined, verification: undefined, challenge: { ...ch[0].challenge!, problem: "", route: "" as const }, history: [] };
ok(formGaps(blankCh, cfg).missing.includes("The problem") && formGaps(blankCh, cfg).missing.includes("Procurement route"), "challenge gaps listed");
s = reducer(s, { type: "dr/saveDraft", app: blankCh } as never);
s = reducer(s, { type: "dr/submit", appId: "dr_new_ch" } as never);
ok(s.dealRoom.apps.find((a) => a.id === "dr_new_ch")!.status === "Draft", "submit refused while gaps remain");
s = reducer(s, { type: "dr/saveDraft", app: { ...blankCh, challenge: ch[0].challenge } } as never);
s = reducer(s, { type: "dr/submit", appId: "dr_new_ch" } as never);
const sub = s.dealRoom.apps.find((a) => a.id === "dr_new_ch")!;
ok(sub.status === "Submitted" && sub.ref?.startsWith("CA3-FP-") && sub.verification?.state === "Verification pending", "challenge submits into verification: " + sub.status);
