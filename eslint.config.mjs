import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

/** Imports a workspace may not make: the boundaries of docs/architecture.md, checked on every lint. */
const forbid = (files, patterns) => ({
  files,
  rules: { "no-restricted-imports": ["error", { patterns }] },
});

/** The API's layers (docs/architecture.md, "The API process"). Later entries override earlier ones for the same files. */
function apiLayers() {
  const db = { group: ["@excursia/db", "@prisma/*", "pg"], allowTypeImports: true, message: "Only *.repo.ts files query the database." };
  const repo = { group: ["**/*.repo"], message: "Only a service calls a repository." };
  const service = { group: ["**/*.service"], message: "Routes call controllers; controllers call services." };
  const layer = (files, patterns, ignores = []) => ({
    files,
    ignores,
    rules: { "@typescript-eslint/no-restricted-imports": ["error", { patterns }] },
  });
  return [
    layer(["apps/api/src/**/*.ts"], [db], ["apps/api/src/**/*.repo.ts", "apps/api/src/server.ts", "apps/api/src/cli/**", "apps/api/src/**/index.ts"]),
    layer(["apps/api/src/**/*.controller.ts"], [db, repo]),
    layer(["apps/api/src/**/*.routes.ts"], [db, repo, service]),
  ];
}

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  { settings: { next: { rootDir: "apps/web/" } } },

  // the web app talks to the API over HTTP and never to the database
  forbid(
    ["apps/web/**"],
    [{ group: ["@excursia/db", "@excursia/db/*", "@prisma/*", "pg", "express"], message: "The web app reaches data only through the API (docs/architecture.md)." }],
  ),
  // the rules stay pure, so both the browser and the API can run them
  forbid(
    ["packages/domain/src/**"],
    [{ group: ["react", "react-dom", "next", "next/*", "@excursia/db", "@excursia/db/*", "@prisma/*", "pg", "express"], message: "Rules are pure: no React, Next.js, HTTP or database (docs/architecture.md)." }],
  ),
  // contracts are shapes only
  forbid(
    ["packages/contracts/src/**"],
    [{ group: ["react", "next", "next/*", "@excursia/db", "@excursia/db/*", "@excursia/domain/*", "express"], message: "Contracts hold Zod schemas and types only." }],
  ),
  // the API has no UI
  forbid(["apps/api/**"], [{ group: ["react", "react-dom", "next", "next/*"], message: "The API has no UI." }]),

  // inside the API, each layer reaches only the one below it: routes → controller → service → repo → database.
  // Type imports of the database stay allowed, so modules can be assembled from a Db passed in.
  ...apiLayers(),

  globalIgnores([
    "**/.next/**",
    "**/out/**",
    "**/build/**",
    "**/dist/**",
    "**/next-env.d.ts",
    // the Prisma client, generated by `prisma generate`
    "packages/db/src/generated/**",
  ]),
]);

export default eslintConfig;
